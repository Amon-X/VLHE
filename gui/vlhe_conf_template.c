/* ------------------------------------------------------------------ */
/* The file headers                                                   */
/* ------------------------------------------------------------------ */

static const char header_system[] =
";\n"
"; vlhe.conf - the machine's settings.\n"
";\n"
"; GENERATED. The control centre writes this file, and a new version\n"
"; replaces it wholesale - so a comment added by hand will not survive.\n"
"; Edit the values freely; they are read back as written.\n"
";\n"
"; THE FILE DESCRIBES INTENT. Something else - the init script, or a\n"
"; launcher - translates it into module parameters and command-line\n"
"; arguments. The daemons keep the syntax they already have.\n"
";\n"
"; Every value is the CURRENT DEFAULT unless its comment says\n"
"; otherwise, so a file left exactly as generated behaves as the\n"
"; software does with no config at all.\n"
";\n"
"; SECTION NAMES ARE NAME-AGNOSTIC on purpose: [Midi Settings], not\n"
"; [Vmidi Settings], so this file need not change when program names\n"
"; are settled.\n"
";\n"
"; WHAT IS NOT HERE, deliberately: which image is in each drive (that\n"
"; is state, in /var/lib/vlhe/state/drives), this user's mixer levels and\n"
"; preferences (~/.vlhe/vlhe.conf), the tuning knobs that exist for\n"
"; diagnosis, and the test-harness options.\n"
";\n";

static const char header_user[] =
";\n"
"; vlhe.conf - this user's own settings.\n"
";\n"
"; GENERATED by the control centre, as the machine's file is. Nothing\n"
"; here needs root, and nothing here affects anybody else.\n"
";\n"
"; Mixer levels are the one thing that also appears in the machine's\n"
"; file: that one is a floor applied at boot, and these override it\n"
"; when you log in.\n"
";\n";

static const char header_drives[] =
";\n"
"; drives - which image is in each drive.\n"
";\n"
"; STATE, NOT CONFIGURATION, which is why it is under /var/lib rather\n"
"; than in /etc. The disc daemon maintains it; the control centre asks\n"
"; the daemon rather than writing here itself.\n"
";\n"
"; It is restored at boot, so a machine comes back with the discs it\n"
"; had - no login and no GUI needed.\n"
";\n";

const char *
vlhe_conf_template_header(int file)
{
    switch (file) {
    case VLHE_TPL_USER:   return header_user;
    case VLHE_TPL_DRIVES: return header_drives;
    default:              return header_system;
    }
}

