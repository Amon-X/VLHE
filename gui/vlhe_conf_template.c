int
vlhe_conf_template_defaults(struct vlhe_conf *c, int file)
{
    int i, n = 0;

    c->n = 0;
    for (i = 0; i < vlhe_conf_template_n; i++) {
        if (vlhe_conf_template[i].file != file)
            continue;
        if (vlhe_conf_template[i].disabled)
            continue;           /* documented, but not a live key */
        if (vlhe_conf_set(c, vlhe_conf_template[i].section,
                          vlhe_conf_template[i].key,
                          vlhe_conf_template[i].dflt) < 0)
            break;
        n++;
    }
    return n;
}

/* Has this section already been opened in the output? */
static int
seen_section(const char *const *seen, int nseen, const char *section)
{
    int i;

    for (i = 0; i < nseen; i++) {
        if (strcmp(seen[i], section) == 0)
            return 1;
    }
    return 0;
}

/* Format the whole file into `fp'.
 *
 * WRITTEN STRAIGHT TO THE STREAM, NOT INTO A BUFFER. The first version
 * built the text in a fixed `char body[]' and stopped when it filled -
 * SILENTLY, producing a valid-looking file that had lost 22 of its 23
 * keys. The test caught it, and the fix is to have no size to
 * overrun: the comments alone are several thousand bytes and a bound
 * that has to be maintained by hand is a bound that will be wrong
 * again. */
static int
format_file(FILE *fp, const struct vlhe_conf *c, int file)
{
    const char *seen[VLHE_CONF_MAX_ENTRIES];
    int nseen = 0;
    int i, j;
    int written[VLHE_CONF_MAX_ENTRIES];

    for (i = 0; i < c->n; i++)
        written[i] = 0;

    /* Template order first, each key under its section header with its
     * comment above it. */
    for (i = 0; i < vlhe_conf_template_n; i++) {
        const struct vlhe_tpl_entry *t = &vlhe_conf_template[i];
        const char *value;
        int found = -1;

        if (t->file != file)
            continue;

        for (j = 0; j < c->n; j++) {
            if (strcmp(c->entry[j].section, t->section) == 0 &&
                strcmp(c->entry[j].key, t->key) == 0) {
                found = j;
                break;
            }
        }
        value = found >= 0 ? c->entry[found].value : t->dflt;

        if (!seen_section(seen, nseen, t->section)) {
            if (nseen < VLHE_CONF_MAX_ENTRIES)
                seen[nseen++] = t->section;
            if (fprintf(fp, "\n[%s]\n", t->section) < 0)
                return -1;
        }

        if (t->comment != NULL) {
            if (fprintf(fp, "\n%s\n", t->comment) < 0)
                return -1;
        }

        if (fprintf(fp, "%s%s = %s\n",
                    t->disabled ? "; " : "", t->key, value) < 0)
            return -1;

        if (found >= 0)
            written[found] = 1;

        /* IS THIS THE TEMPLATE'S LAST KEY IN THIS SECTION? If so, any
         * of the user's keys that belong here go NOW, under this
         * header - not at the end of the file, where they would land
         * beneath whichever section happened to be written last and
         * read back as part of it. A retired key quietly changing
         * section is a setting silently moved. */
        {
            int more = 0;

            for (j = i + 1; j < vlhe_conf_template_n; j++) {
                if (vlhe_conf_template[j].file == file &&
                    strcmp(vlhe_conf_template[j].section,
                           t->section) == 0) {
                    more = 1;
                    break;
                }
            }
            if (!more) {
                for (j = 0; j < c->n; j++) {
                    if (written[j])
                        continue;
                    if (strcmp(c->entry[j].section, t->section) != 0)
                        continue;
                    if (fprintf(fp, "%s = %s\n",
                                c->entry[j].key, c->entry[j].value) < 0)
                        return -1;
                    written[j] = 1;
                }
            }
        }
    }

    /* WHOLE SECTIONS THE TEMPLATE DOES NOT KNOW, kept rather than
     * dropped - a key we stopped recognising is still the user's.
     * Keys in a section the template DOES know were already emitted
     * under their own header, above. */
    for (j = 0; j < c->n; j++) {
        if (written[j])
            continue;
        if (!seen_section(seen, nseen, c->entry[j].section)) {
            if (nseen < VLHE_CONF_MAX_ENTRIES)
                seen[nseen++] = c->entry[j].section;
            if (fprintf(fp, "\n[%s]\n", c->entry[j].section) < 0)
                return -1;
        }
        if (fprintf(fp, "%s = %s\n",
                    c->entry[j].key, c->entry[j].value) < 0)
            return -1;
    }

    return 0;
}

int
vlhe_conf_template_write(const struct vlhe_conf *c, const char *path,
                         int file, int backup)
{
    return vlhe_conf_write_fn(path, vlhe_conf_template_header(file),
                              format_file, c, file, backup);
}
